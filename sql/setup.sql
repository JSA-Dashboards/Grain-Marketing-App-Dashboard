-- Grain Marketing Desk -> Snowflake: one-time setup
-- Column order matches the CSV files from the app's "Export for Snowflake".
-- Every table has EXPORTED_AT so each export is kept as a snapshot; the *_CURRENT
-- views show the latest export. Safe to re-run: nothing is dropped.

USE ROLE GRAIN_MARKETING_ROLE;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE GRAIN_MARKETING;
CREATE SCHEMA IF NOT EXISTS GRAIN_MARKETING.MARKETING;
USE SCHEMA GRAIN_MARKETING.MARKETING;

CREATE FILE FORMAT IF NOT EXISTS GRAIN_DESK_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE NULL_IF = ('') ENCODING = 'UTF8';
CREATE STAGE IF NOT EXISTS GRAIN_DESK_STAGE FILE_FORMAT = GRAIN_DESK_CSV;

CREATE TABLE IF NOT EXISTS FARMS (
  EXPORTED_AT TIMESTAMP_TZ,
  FARM_ID VARCHAR,
  FARM_NAME VARCHAR,
  BROKER VARCHAR,
  IS_SAMPLE BOOLEAN,
  UPDATED_AT TIMESTAMP_TZ,
  STATE VARCHAR,
  COUNTY VARCHAR
);
ALTER TABLE FARMS ADD COLUMN IF NOT EXISTS STATE VARCHAR;
ALTER TABLE FARMS ADD COLUMN IF NOT EXISTS COUNTY VARCHAR;

CREATE TABLE IF NOT EXISTS CROP_PLANS (
  EXPORTED_AT TIMESTAMP_TZ,
  FARM_ID VARCHAR,
  CROP_PLAN_ID VARCHAR,
  CROP_YEAR NUMBER(4,0),
  CROP VARCHAR,
  ACRES NUMBER(12,2),
  APH_YIELD NUMBER(10,2),
  EXPECTED_YIELD NUMBER(10,2),
  COST_PER_ACRE NUMBER(12,2),
  INSURANCE_PLAN VARCHAR,
  COVERAGE_PCT NUMBER(5,2),
  PROJECTED_PRICE NUMBER(10,4),
  HARVEST_PRICE NUMBER(10,4),
  EXPECTED_BU NUMBER(14,2),
  TOTAL_COST NUMBER(16,2),
  BREAKEVEN_PER_BU NUMBER(10,4),
  DYNAMIC_BREAKEVEN NUMBER(10,4),
  INSURED_BU NUMBER(14,2),
  REVENUE_GUARANTEE NUMBER(16,2),
  BUDGET_YIELD NUMBER(10,2),
  ACTUAL_YIELD NUMBER(10,2),
  BUDGET_COST_PER_ACRE NUMBER(12,2),
  ACTUAL_COST_PER_ACRE NUMBER(12,2),
  GOV_PAY_PER_ACRE NUMBER(12,2),
  INS_PAY_PER_ACRE NUMBER(12,2)
);
-- added 2026-10-07 for budget vs actual (no-op once present)
ALTER TABLE CROP_PLANS ADD COLUMN IF NOT EXISTS BUDGET_YIELD NUMBER(10,2);
ALTER TABLE CROP_PLANS ADD COLUMN IF NOT EXISTS ACTUAL_YIELD NUMBER(10,2);
ALTER TABLE CROP_PLANS ADD COLUMN IF NOT EXISTS BUDGET_COST_PER_ACRE NUMBER(12,2);
ALTER TABLE CROP_PLANS ADD COLUMN IF NOT EXISTS ACTUAL_COST_PER_ACRE NUMBER(12,2);
-- added 2026-10-20: payments that lower the break-even (BREAKEVEN_PER_BU is after them)
ALTER TABLE CROP_PLANS ADD COLUMN IF NOT EXISTS GOV_PAY_PER_ACRE NUMBER(12,2);
ALTER TABLE CROP_PLANS ADD COLUMN IF NOT EXISTS INS_PAY_PER_ACRE NUMBER(12,2);

CREATE TABLE IF NOT EXISTS CONTRACTS (
  EXPORTED_AT TIMESTAMP_TZ,
  FARM_ID VARCHAR,
  CONTRACT_ID VARCHAR,
  CROP_YEAR NUMBER(4,0),
  CROP VARCHAR,
  CONTRACT_TYPE VARCHAR,
  IS_HEDGE BOOLEAN,
  DATE_MADE DATE,
  CONTRACT_NO VARCHAR,
  BUYER VARCHAR,
  DELIVERY_LOCATION VARCHAR,
  DELIVERY_SOURCE VARCHAR,
  BUSHELS NUMBER(14,2),
  FUTURES_MONTH VARCHAR,
  FUTURES_OR_PRICE NUMBER(10,4),
  BASIS NUMBER(10,4),
  FLAT_PRICE NUMBER(10,4),
  PRICED_VALUE NUMBER(16,2),
  PREMIUM NUMBER(10,4),
  NEEDS_PRICING BOOLEAN,
  DELIVERY_START DATE,
  DELIVERY_END DATE,
  TRACK_LOADS BOOLEAN,
  DELIVERED_BU NUMBER(14,2),
  REMAINING_BU NUMBER(14,2),
  STATUS VARCHAR,
  NOTES VARCHAR,
  ACC_MAX_BU NUMBER(14,2),
  ACC_KNOCK_OUT NUMBER(10,4),
  ACC_RATE_BU NUMBER(14,2),
  ACC_RATE_PERIOD VARCHAR,
  ACC_DOUBLE_UP BOOLEAN,
  ACC_START DATE,
  ACC_EXPIRATION DATE,
  ACC_KNOCKED_OUT BOOLEAN,
  ACC_KNOCK_OUT_DATE DATE,
  PP_STRIKE NUMBER(10,4),
  PP_EXPIRATION DATE,
  PP_DOUBLE_BU NUMBER(14,2),
  PP_OUTCOME VARCHAR,
  MM_MIN NUMBER(10,4),
  MM_MAX NUMBER(10,4),
  MM_FEE NUMBER(10,4),
  MM_EXPIRATION DATE,
  OTHER_NAME VARCHAR,
  OTHER_KEY_DATE DATE,
  OTHER_TERMS VARCHAR,
  ROLL_COUNT NUMBER(4,0),
  ROLL_SPREAD NUMBER(10,4),
  ROLL_FEES_PER_BU NUMBER(10,4),
  FUTURES_AFTER_ROLLS NUMBER(10,4),
  DEFERRED BOOLEAN,
  PAY_DATE DATE
);
-- added 2026-10-14 for rolls on HTAs and futures hedges (no-op once present)
ALTER TABLE CONTRACTS ADD COLUMN IF NOT EXISTS ROLL_COUNT NUMBER(4,0);
ALTER TABLE CONTRACTS ADD COLUMN IF NOT EXISTS ROLL_SPREAD NUMBER(10,4);
ALTER TABLE CONTRACTS ADD COLUMN IF NOT EXISTS ROLL_FEES_PER_BU NUMBER(10,4);
ALTER TABLE CONTRACTS ADD COLUMN IF NOT EXISTS FUTURES_AFTER_ROLLS NUMBER(10,4);
-- added 2026-10-20 for deferred payment contracts
ALTER TABLE CONTRACTS ADD COLUMN IF NOT EXISTS DEFERRED BOOLEAN;
ALTER TABLE CONTRACTS ADD COLUMN IF NOT EXISTS PAY_DATE DATE;

-- one row per roll (HTA or futures hedge moved to a later futures month)
CREATE TABLE IF NOT EXISTS ROLLS (
  EXPORTED_AT TIMESTAMP_TZ,
  FARM_ID VARCHAR,
  CONTRACT_ID VARCHAR,
  ROLL_ID VARCHAR,
  ROLL_DATE DATE,
  FROM_MONTH VARCHAR,
  TO_MONTH VARCHAR,
  SPREAD NUMBER(10,4),
  FEE_PER_BU NUMBER(10,4),
  FEE_TOTAL_USD NUMBER(14,2),
  NOTE VARCHAR
);

CREATE TABLE IF NOT EXISTS LOADS (
  EXPORTED_AT TIMESTAMP_TZ,
  FARM_ID VARCHAR,
  CONTRACT_ID VARCHAR,
  LOAD_ID VARCHAR,
  DELIVERY_DATE DATE,
  SCALE_TICKET VARCHAR,
  NET_BU NUMBER(14,2),
  MOISTURE_PCT NUMBER(5,2),
  DISCOUNTS_USD NUMBER(12,2),
  NOTES VARCHAR
);

CREATE TABLE IF NOT EXISTS PRICING_EVENTS (
  EXPORTED_AT TIMESTAMP_TZ,
  FARM_ID VARCHAR,
  CONTRACT_ID VARCHAR,
  EVENT_ID VARCHAR,
  PRICED_DATE DATE,
  LEG VARCHAR,
  VALUE NUMBER(10,4),
  FUTURES_MONTH VARCHAR,
  NOTE VARCHAR
);

CREATE TABLE IF NOT EXISTS BINS (
  EXPORTED_AT TIMESTAMP_TZ,
  FARM_ID VARCHAR,
  BIN_ID VARCHAR,
  BIN_NAME VARCHAR,
  LOCATION VARCHAR,
  CAPACITY_BU NUMBER(14,2),
  CROP VARCHAR,
  BUSHELS NUMBER(14,2),
  MOISTURE_PCT NUMBER(5,2),
  LAST_CHECKED DATE
);

CREATE OR REPLACE VIEW FARMS_CURRENT AS
  SELECT * FROM FARMS WHERE EXPORTED_AT = (SELECT MAX(EXPORTED_AT) FROM FARMS);
CREATE OR REPLACE VIEW CROP_PLANS_CURRENT AS
  SELECT * FROM CROP_PLANS WHERE EXPORTED_AT = (SELECT MAX(EXPORTED_AT) FROM CROP_PLANS);
CREATE OR REPLACE VIEW CONTRACTS_CURRENT AS
  SELECT * FROM CONTRACTS WHERE EXPORTED_AT = (SELECT MAX(EXPORTED_AT) FROM CONTRACTS);
CREATE OR REPLACE VIEW LOADS_CURRENT AS
  SELECT * FROM LOADS WHERE EXPORTED_AT = (SELECT MAX(EXPORTED_AT) FROM LOADS);
CREATE OR REPLACE VIEW PRICING_EVENTS_CURRENT AS
  SELECT * FROM PRICING_EVENTS WHERE EXPORTED_AT = (SELECT MAX(EXPORTED_AT) FROM PRICING_EVENTS);
CREATE OR REPLACE VIEW ROLLS_CURRENT AS
  SELECT * FROM ROLLS WHERE EXPORTED_AT = (SELECT MAX(EXPORTED_AT) FROM ROLLS);
CREATE OR REPLACE VIEW BINS_CURRENT AS
  SELECT * FROM BINS WHERE EXPORTED_AT = (SELECT MAX(EXPORTED_AT) FROM BINS);
