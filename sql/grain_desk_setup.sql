-- Grain Marketing Desk (Streamlit version): Snowflake setup. Run once, as a role that can create schemas
-- and roles (SYSADMIN for the schema, SECURITYADMIN for the grants). Safe to re-run: nothing is dropped.
USE ROLE SYSADMIN;
CREATE SCHEMA IF NOT EXISTS JSA.GRAIN_DESK;
USE SCHEMA JSA.GRAIN_DESK;

CREATE SEQUENCE IF NOT EXISTS GD_SEQ START = 1 INCREMENT = 1;

CREATE TABLE IF NOT EXISTS DOCS (
  PATH VARCHAR PRIMARY KEY, COLL VARCHAR NOT NULL, ID VARCHAR NOT NULL,
  DATA VARCHAR NOT NULL,                 -- the JSON document
  VERSION NUMBER NOT NULL, SEQ NUMBER NOT NULL, BROKER_UID VARCHAR,
  DELETED BOOLEAN NOT NULL DEFAULT FALSE, UPDATED_AT TIMESTAMP_TZ
);
CREATE TABLE IF NOT EXISTS USERS (
  ID VARCHAR PRIMARY KEY, EMAIL VARCHAR NOT NULL, NAME VARCHAR NOT NULL, ROLE VARCHAR NOT NULL,
  ACTIVE BOOLEAN NOT NULL DEFAULT TRUE, CREATED_AT TIMESTAMP_TZ, LAST_LOGIN TIMESTAMP_TZ
);
CREATE TABLE IF NOT EXISTS LOGIN_CODES (HASH VARCHAR, USER_ID VARCHAR, EXPIRES FLOAT, TRIES NUMBER DEFAULT 0);
CREATE TABLE IF NOT EXISTS SESSIONS (HASH VARCHAR, USER_ID VARCHAR, EXPIRES FLOAT);
CREATE TABLE IF NOT EXISTS ASSETS (
  ID VARCHAR PRIMARY KEY, OWNER_UID VARCHAR, CONTENT_TYPE VARCHAR, SIZE NUMBER, DATA BINARY, CREATED_AT TIMESTAMP_TZ
);

-- One role for the app AND the nightly jobs: full access to its own schema, read-only on the source tables.
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS GRAIN_DESK_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE GRAIN_DESK_ROLE;
GRANT USAGE ON DATABASE JSA TO ROLE GRAIN_DESK_ROLE;
GRANT USAGE ON SCHEMA JSA.GRAIN_DESK TO ROLE GRAIN_DESK_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA JSA.GRAIN_DESK TO ROLE GRAIN_DESK_ROLE;
GRANT USAGE ON SEQUENCE JSA.GRAIN_DESK.GD_SEQ TO ROLE GRAIN_DESK_ROLE;
GRANT USAGE ON SCHEMA JSA.BASIS_TRACKER TO ROLE GRAIN_DESK_ROLE;
GRANT SELECT ON TABLE JSA.BASIS_TRACKER.FUTURES_PRICES TO ROLE GRAIN_DESK_ROLE;
GRANT SELECT ON TABLE JSA.BASIS_TRACKER.SNAPSHOTS TO ROLE GRAIN_DESK_ROLE;
GRANT SELECT ON TABLE JSA.BASIS_TRACKER.SNAPSHOT_ROWS TO ROLE GRAIN_DESK_ROLE;
GRANT SELECT ON TABLE JSA.BASIS_TRACKER.LOCATION_META TO ROLE GRAIN_DESK_ROLE;
GRANT SELECT ON TABLE JSA.BASIS_TRACKER.GRAIN_MAP TO ROLE GRAIN_DESK_ROLE;
GRANT USAGE ON SCHEMA JSA.CME_FEEDER_CATTLE TO ROLE GRAIN_DESK_ROLE;
GRANT SELECT ON TABLE JSA.CME_FEEDER_CATTLE.FCI_DAILY TO ROLE GRAIN_DESK_ROLE;

